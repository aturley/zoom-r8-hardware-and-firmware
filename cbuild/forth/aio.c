/* Audio in and out on McASP0, polled through RBUF/XBUF on the configuration bus.
   Set up as the running stock firmware had it (../synth/stockstate.h and data/PERIPH.BIN): I2S, two 32-bit slots,
   24-bit left-justified, MSB first. Bit clock = AHCLKX (external oscillator) / 4, frame sync generated by the
   transmitter; the receiver runs synchronously (ACLKXCTL.ASYNC = 0) on the same clocks.
   Serializer 1 receives (the ADC), serializers 2 and 4 transmit (both get the same data, as the synth does). */
#include "aio.h"
#include "stockstate.h"
#define M(o) REG(MCASP0 + (o))
#define PFUNC 0x10
#define PDIR 0x14
#define GBLCTL 0x44
#define AMUTE 0x48
#define DLBCTL 0x4C
#define DITCTL 0x50
#define RGBLCTL 0x60
#define RMASK 0x64
#define RFMT 0x68
#define AFSRCTL 0x6C
#define ACLKRCTL 0x70
#define AHCLKRCTL 0x74
#define RTDM 0x78
#define RINTCTL 0x7C
#define RSTAT 0x80
#define RCLKCHK 0x88
#define REVTCTL 0x8C
#define XGBLCTL 0xA0
#define XMASK 0xA4
#define XFMT 0xA8
#define AFSXCTL 0xAC
#define ACLKXCTL 0xB0
#define AHCLKXCTL 0xB4
#define XTDM 0xB8
#define XINTCTL 0xBC
#define XSTAT 0xC0
#define XCLKCHK 0xC8
#define XEVTCTL 0xCC
#define SRCTL(n) (0x180 + 4 * (n))
#define XBUF(n) (0x200 + 4 * (n))
#define RBUF(n) (0x200 + 4 * (n))     /* same offsets as XBUF: a serializer is one or the other */
/* receive side, as captured from stock (only the format matters: the receiver uses the transmit clocks) */
#define STOCK_RMASK     0xFFFFFF00u
#define STOCK_RFMT      0x000180F0u
#define STOCK_AFSRCTL   0x00000113u
#define STOCK_ACLKRCTL  0x0000002Fu
#define STOCK_AHCLKRCTL 0x00000000u
#define STOCK_RTDM      0x00000003u
#define STOCK_RCLKCHK   0x02FF0008u
#define STOCK_SRCTL1    0x0000000Eu
/* GBLCTL bits: receive in the low byte, transmit in the next */
#define HCLKRST (1u << 1)
#define CLKRST  (1u << 0)
#define SRCLR   (1u << 2)
#define SMRST   (1u << 3)
#define FRST    (1u << 4)
#define DATA  (1u << 5)                 /* RSTAT.RDATA / XSTAT.XDATA */
#define ERRS  0x107u                    /* overrun/underrun, sync error, clock fail, ERR */
/* LCD pins (lcd.c) keep their current state when the stock GPIO state is applied */
#define LCD_B23 (1u << 14)
#define LCD_B8  ((1u << 9) | (1u << 8))

int aio_ok;
volatile u32 aio_errs;
s32 aio_peak[2];
u32 aio_frames;

static void gpio_stock(void)
{
    for (int i = 0; i < 5; i++) {
        u32 off = STOCK_GPIO[i][0];
        u32 keep = off == 0x38 ? LCD_B23 : off == 0xB0 ? LCD_B8 : 0;
        u32 out = REG(GPIO + off + G_OUT), dir = REG(GPIO + off + G_DIR);
        REG(GPIO + off + G_OUT) = (out & keep) | (STOCK_GPIO[i][2] & ~keep);
        REG(GPIO + off + G_DIR) = (dir & keep) | (STOCK_GPIO[i][1] & ~keep);
    }
}
static int gbl(u32 bits)        /* set GBLCTL bits (receive and transmit both), wait (<= 5 ms) for them to latch */
{
    u32 v = M(GBLCTL) | bits;
    M(RGBLCTL) = v & 0x1Fu; M(XGBLCTL) = v & 0x1F00u;
    u32 t0 = TSCL;
    while ((M(GBLCTL) & bits) != bits) if (TSCL - t0 > CPU_HZ / 200) return 0;
    return 1;
}
#define BOTH(b) ((b) | ((b) << 8))
int aio_init(void)
{
    gpio_stock();
    psc_enable(PSC1, 7);
    M(GBLCTL) = 0; M(RGBLCTL) = 0; M(XGBLCTL) = 0;
    M(RMASK) = STOCK_RMASK; M(RFMT) = STOCK_RFMT | (1u << 3);      /* RBUSEL: CPU reads RBUF on the config bus */
    M(AFSRCTL) = STOCK_AFSRCTL; M(ACLKRCTL) = STOCK_ACLKRCTL; M(AHCLKRCTL) = STOCK_AHCLKRCTL;
    M(RTDM) = STOCK_RTDM; M(RINTCTL) = 0; M(RCLKCHK) = STOCK_RCLKCHK; M(REVTCTL) = 1;
    M(XMASK) = STOCK_XMASK; M(XFMT) = STOCK_XFMT | (1u << 3);      /* XBUSEL */
    M(AFSXCTL) = STOCK_AFSXCTL; M(ACLKXCTL) = STOCK_ACLKXCTL;
    M(AHCLKXCTL) = STOCK_AHCLKXCTL;                                 /* AHCLKX is an input: never drive it */
    M(XTDM) = STOCK_XTDM; M(XINTCTL) = 0; M(XCLKCHK) = STOCK_XCLKCHK; M(XEVTCTL) = 1;
    for (int n = 0; n < 16; n++) M(SRCTL(n)) = 0;
    M(SRCTL(1)) = STOCK_SRCTL1; M(SRCTL(2)) = STOCK_SRCTL2; M(SRCTL(4)) = STOCK_SRCTL4;
    M(PFUNC) = STOCK_PFUNC; M(PDIR) = STOCK_PDIR;
    M(DITCTL) = 0; M(DLBCTL) = 0; M(AMUTE) = 0;
    int ok = gbl(BOTH(HCLKRST)) && gbl(BOTH(CLKRST));
    M(RSTAT) = 0xFFFF; M(XSTAT) = 0xFFFF;
    ok = ok && gbl(BOTH(SRCLR));
    M(XBUF(2)) = 0; M(XBUF(4)) = 0;                                 /* service the first slot before starting */
    ok = ok && gbl(BOTH(SMRST)) && gbl(BOTH(FRST));
    aio_ok = ok;
    return ok;
}

/* Restart the transmitter, clocks left running (the receiver uses them too). Needed after any underrun: measured on
   the R8, the first XBUF write after an underrun stalls the transmitter (XRDY stays 0, XDATA never sets again)
   until XFRST is cleared and set again. Between AUDIO-INIT and PASS nothing feeds it, so it always has underrun. */
static void tx_restart(void)
{
    M(XGBLCTL) = BOTH(HCLKRST | CLKRST) & 0x1F00u;
    u32 t0 = TSCL;
    while (M(GBLCTL) & ((SRCLR | SMRST | FRST) << 8)) if (TSCL - t0 > CPU_HZ / 200) break;
    M(XSTAT) = 0xFFFF;
    gbl(SRCLR << 8);
    M(XBUF(2)) = 0; M(XBUF(4)) = 0;
    gbl(SMRST << 8); gbl(FRST << 8);
}

/* Copy input to output for ms milliseconds, polled. The channel of each slot comes from the McASP itself, not from
   counting: RSTAT.RTDMSLT / XSTAT.XTDMSLT say whether the slot now on the wire is even. RBUF holds the slot before
   it and XBUF feeds the slot after it, so both have the opposite parity: channel = TDMSLT (0 = left, 1 = right).
   (If the bit's sense were the other way round, both sides would flip together and channels would still match.)
   gain is Q8 (256 = unity). Peaks are the largest |sample| per channel, 24-bit full scale = 8388607. */
void aio_pass(u32 ms, s32 gain)
{
    s32 last[2] = { 0, 0 };
    u32 n = 0;
    aio_peak[0] = aio_peak[1] = 0; aio_errs = 0;
    if (!aio_ok) return;
    tx_restart();
    (void)M(RBUF(1));                                               /* stale slot, then the errors from the idle time */
    M(RSTAT) = ERRS; M(XSTAT) = ERRS;
    u32 t0 = TSCL, span = ms * (CPU_HZ / 1000);
    while (TSCL - t0 < span) {
        u32 rs = M(RSTAT);
        if (rs & DATA) {
            s32 v = (s32)M(RBUF(1)) >> 8;
            int c = (rs >> 3) & 1;
            last[c] = v;
            s32 a = v < 0 ? -v : v;
            if (a > aio_peak[c]) aio_peak[c] = a;
            n++;
        }
        u32 xs = M(XSTAT);
        if (xs & DATA) {
            s32 v = (s32)(((long long)last[(xs >> 3) & 1] * gain) >> 8);
            if (v > 8388607) v = 8388607; else if (v < -8388608) v = -8388608;
            u32 w = (u32)v << 8;
            M(XBUF(2)) = w; M(XBUF(4)) = w;
        }
        if ((rs | xs) & ERRS) {
            if (n > 4) aio_errs++;                                  /* the first slot after idle time may race */
            M(RSTAT) = rs & ERRS; M(XSTAT) = xs & ERRS;
            if (xs & 1) tx_restart();                               /* underrun: restart before writing again */
        }
    }
    aio_frames = n / 2;
}
